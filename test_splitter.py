"""句子拆分測試 — 針對最容易出 silent bug 的邊界情況。

跑法：uv run python test_splitter.py
"""

from splitter import split_sentences

CASES = [
    # (說明, 輸入, 期望輸出)
    ("基本句號",
     "他走了。我留下。",
     ["他走了。", "我留下。"]),

    ("收尾引號黏合",
     "「你好。」然後他走了。",
     ["「你好。」", "然後他走了。"]),

    ("冒號是句內標點，不切",
     "他說（很大聲）：「走吧。」",
     ["他說（很大聲）：「走吧。」"]),

    ("連續問號驚嘆號算一句",
     "真的嗎？！我不敢相信！",
     ["真的嗎？！", "我不敢相信！"]),

    ("雙省略號 = 句界",
     "他走了……然後……",
     ["他走了……", "然後……"]),

    ("連續重複句號壓成 1 個",
     "好。。。走吧。",
     ["好。", "走吧。"]),

    ("多重省略號壓成雙",
     "好…………走吧。",
     ["好……", "走吧。"]),

    ("單省略號接中文字 = 不切",
     "我不知道…他走了。",
     ["我不知道…他走了。"]),

    ("小數點不切",
     "圓周率是 3.14，約等於 22/7。",
     ["圓周率是 3.14，約等於 22/7。"]),

    ("句內逗號頓號不切",
     "今天下雨，明天晴。帶傘，帶帽。",
     ["今天下雨，明天晴。", "帶傘，帶帽。"]),

    ("換行 = 段落邊界",
     "第一段。\n第二段。",
     ["第一段。", "第二段。"]),

    ("純標點片段丟棄",
     "好。。。。。走吧。",
     ["好。", "走吧。"]),

    ("分號切句",
     "他站著；她坐著。",
     ["他站著；", "她坐著。"]),

    ("半形標點",
     "Really? Yes!",
     ["Really?", "Yes!"]),

    ("引號開頭不殘留收尾符號",
     "「第一句。」\n「第二句。」",
     ["「第一句。」", "「第二句。」"]),

    ("句末無標點",
     "這是最後一句沒有標點",
     ["這是最後一句沒有標點"]),

    ("簡體輸入",
     "这个苹果很甜。",
     ["这个苹果很甜。"]),
]


def main():
    failed = 0
    for name, src, want in CASES:
        got = split_sentences(src)
        ok = got == want
        failed += not ok
        mark = "PASS" if ok else "FAIL"
        print(f"[{mark}] {name}")
        if not ok:
            print(f"       輸入: {src!r}")
            print(f"       期望: {want}")
            print(f"       實際: {got}")
    print(f"\n{len(CASES) - failed}/{len(CASES)} 通過")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
